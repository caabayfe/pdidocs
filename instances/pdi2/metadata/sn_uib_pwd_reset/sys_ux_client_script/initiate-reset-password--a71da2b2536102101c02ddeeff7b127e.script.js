/**
 * @param {params} params
 * @param {api} params.api
 * @param {any} params.event
 * @param {any} params.imports
 * @param {ApiHelpers} params.helpers
 */
async function handler({
    api,
    event,
    helpers,
    imports
}) {
    const pwdResetUtil = imports["sn_uib_pwd_reset.PwdResetUxfClientUtil"]();
    const resetPageDetails = api.data.get_pwd_reset_page_details.output;
    const pageDetails = {
        ...api.state.pageDetails
    };
    if (!pageDetails.isAutoGeneratedPassword) {
        const {
            isPasswordPolicyEnabled
        } = resetPageDetails.passwordPolicy;
        if (!isPasswordPolicyEnabled) {
            api.emit("PWD_RESET_UIB#SHOW_ERROR_PAGE_FROM_RESET", {
                "errorPageObj": {
                    "actions": {
                        "close": {
                            "isHidden": false,
                            "variant": "secondary"
                        },
                        "createRecord": {
                            "isHidden": false,
                            "variant": "primary"
                        }
                    },
                    "heading": await pwdResetUtil.getTranslation(
                        helpers,
                        "Technical error has occured, try again!"
                    ),
                    "subHeading": "<div>" + await pwdResetUtil.getTranslation(
                        helpers,
                        "There is a configuration error in your system. Contact your System Administrator to know more."
                    ) + "</div>",
                    "shortDescription": await pwdResetUtil.getTranslation(
                        helpers,
                        "Unable to reset user's password because password policy is not enabled"
                    ),
                    "icon": "error"
                }
            });
            return;
        }
        pageDetails.isAcceptPassword = true;
        api.setState("pageDetails", pageDetails);
    } else {
        api.setState("isResetButtonDisabled", true);
        api.setState("isUnlockButtonDisabled", true);
        api.data.initialize_pwd_reset_workflow.execute({
            token: api.state.token,
            newPassword: null
        });
    }
}
