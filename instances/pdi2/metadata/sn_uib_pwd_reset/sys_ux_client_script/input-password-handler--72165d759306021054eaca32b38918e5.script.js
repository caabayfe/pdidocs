/**
 * @param {params} params
 * @param {api} params.api
 * @param {any} params.event
 * @param {any} params.imports
 * @param {ApiHelpers} params.helpers
 */
async function handler({
    api,
    event,
    helpers,
    imports
}) {
    const resetDetails = api.data.get_pwd_reset_page_details.output;
    if (!resetDetails || !Object.keys(resetDetails).length) return;

    const {
        isProcessSupportReset,
        isCredStoreAcceptPassword,
        isAutoGeneratedPassword
    } = resetDetails.data;

    if (!(isProcessSupportReset && isCredStoreAcceptPassword && !isAutoGeneratedPassword)) return;

    const pwdResetUtil = imports["sn_uib_pwd_reset.PwdResetUxfClientUtil"]();
    const inputNewPassword = {
        ...api.state.inputNewPassword
    };
    const inputNewPasswordConfirmation = {
        ...api.state.inputNewPasswordConfirmation
    };

    switch (event.name) {
        case "PWD_RESET_UIB#INPUT_NEW_PASSWORD":
            const passwordPolicyUXF = imports["global.PasswordPolicyUXF"]();
            const passwordPolicyRules = {
                ...api.state.passwordPolicyRules
            };

            inputNewPassword.value = event.payload.value;
            const isNewPasswordNil = !inputNewPassword.value;

            const isPasswordPolicyEnabled = resetDetails.passwordPolicy.isPasswordPolicyEnabled,
                isPasswordStrengthEnabled = resetDetails.passwordStrength.isPasswordStrengthEnabled;

            if (isPasswordPolicyEnabled) {
                if (isPasswordStrengthEnabled) {
                    const {
                        strengthCalRegexList,
                        characterLimit,
                        characterCount,
                        similarAscendingDescendingCount,
                        splCharLimit
                    } = resetDetails.passwordStrength.strengthRuleParams;

                    // Converting regex strings to regex objects
                    const strengthCalRegexObjList = strengthCalRegexList.map(function(regex) {
                        return new RegExp(regex.slice(1, -1));
                    });

                    const strengthCalc = passwordPolicyUXF.getPasswordStrengthCalculator(
                        strengthCalRegexObjList,
                        characterLimit,
                        characterCount,
                        similarAscendingDescendingCount,
                        splCharLimit
                    );
                    const strengthScore = passwordPolicyUXF.getPasswordStrength(strengthCalc, inputNewPassword.value);
                    pwdResetUtil.setPasswordMeterState(isNewPasswordNil, strengthScore, api, helpers);
                }
                let isPasswordValid = true;
                passwordPolicyRules.rulesWithRegex = passwordPolicyRules.rulesWithRegex.map(function(rule) {
                    let ruleObj = {
                        regex: rule.regex,
                        hint: rule.hint,
                        must: rule.must,
                        isValid: false,
                        isInitialIconHidden: false,
                        isValidIconHidden: true,
                        isInvalidIconHidden: true,
                    };
                    if (inputNewPassword.value) {
                        const isValid = new RegExp(rule.regex).test(inputNewPassword.value);
                        isPasswordValid = (isPasswordValid && isValid);
                        ruleObj.isValid = isValid;
                        ruleObj.isInitialIconHidden = true;
                        ruleObj.isValidIconHidden = !isValid;
                        ruleObj.isInvalidIconHidden = isValid;
                    }
                    return ruleObj;
                });
                inputNewPassword.isValid = isPasswordValid;
                api.setState("passwordPolicyRules", passwordPolicyRules);
            }

            let inputNewPasswordFieldMessage = {
                value: [{
                    content: "",
                    icon: "",
                    status: ""
                }],
                isInvalid: false
            };
            if (inputNewPassword.value && !inputNewPassword.isValid) {
                inputNewPasswordFieldMessage = {
                    value: [{
                        content: await pwdResetUtil.getTranslation(
                            helpers,
                            "Entered password doesn't meet the set password criteria."
                        ),
                        icon: pwdResetUtil.uiConstants.CIRCLE_EXCLAMATION_OUTLINE_ICON,
                        status: pwdResetUtil.uiConstants.CRITICAL
                    }],
                    isInvalid: true
                };
            }
            inputNewPassword.fieldMessage = inputNewPasswordFieldMessage;
            api.setState("inputNewPassword", inputNewPassword);
            break;
        case "PWD_RESET_UIB#INPUT_NEW_PASSWORD_CONFIRMATION":
            inputNewPasswordConfirmation.value = event.payload.value;
            break;
    }
    inputNewPasswordConfirmation.isValid = Boolean(
        inputNewPassword.value &&
        inputNewPassword.isValid &&
        inputNewPasswordConfirmation.value &&
        (inputNewPassword.value === inputNewPasswordConfirmation.value)
    );
    let inputNewPasswordConfirmationFieldMessage = {
        value: [{
            content: "",
            icon: "",
            status: ""
        }],
        isInvalid: false
    };
    if (inputNewPassword.value &&
        inputNewPasswordConfirmation.value &&
        (inputNewPassword.value !== inputNewPasswordConfirmation.value)) {
        inputNewPasswordConfirmationFieldMessage = {
            value: [{
                content: await pwdResetUtil.getTranslation(
                    helpers,
                    "The entered passwords don't match."
                ),
                icon: pwdResetUtil.uiConstants.CIRCLE_EXCLAMATION_OUTLINE_ICON,
                status: pwdResetUtil.uiConstants.CRITICAL
            }],
            isInvalid: true,
        };
    }
    inputNewPasswordConfirmation.fieldMessage = inputNewPasswordConfirmationFieldMessage;
    api.setState("inputNewPasswordConfirmation", inputNewPasswordConfirmation);
}
