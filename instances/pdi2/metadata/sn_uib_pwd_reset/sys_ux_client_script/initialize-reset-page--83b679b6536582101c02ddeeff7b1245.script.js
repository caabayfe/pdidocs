/**
 * @param {params} params
 * @param {api} params.api
 * @param {any} params.event
 * @param {any} params.imports
 * @param {ApiHelpers} params.helpers
 */
async function handler({
    api,
    event,
    helpers,
    imports
}) {
    const pwdResetUtil = imports["sn_uib_pwd_reset.PwdResetUxfClientUtil"]();
    const result = api.data.get_pwd_reset_page_details.output ? api.data.get_pwd_reset_page_details.output : {};
    if (!result.isValid) {
        await pwdResetUtil.errorPageRedirection(result, helpers, api);
        return;
    }

    api.setState("token", result.token);
    let pageDetails = { ...api.state.pageDetails
    };
    
    const {
        isProcessSupportReset,
        isCredStoreAcceptPassword,
        isAutoGeneratedPassword
    } = result.data;
    const isLockStateVisible = result.data.isLockStateSubflowMapped;
    let pollingInfo = result.data.pollingInfo;

    pageDetails.isProcessSupportReset = isProcessSupportReset;
    if (isProcessSupportReset) {
        pageDetails.isAutoGeneratedPassword = isAutoGeneratedPassword || !isCredStoreAcceptPassword;
    }
    pageDetails.isAccountUnlockApplicable = result.data.isProcessSupportUnlock;
    pageDetails.isDisplayPassword = result.data.isDisplayPassword;
    pageDetails.isSendEmail = result.data.isSendEmail;
    pollingInfo.refreshRate = pollingInfo.refreshRate ? pollingInfo.refreshRate : pwdResetUtil.uiConstants.REFRESH_RATE;
    pollingInfo.timeOut = pollingInfo.timeOut ? pollingInfo.timeOut : pwdResetUtil.uiConstants.TIMEOUT;
    if (isLockStateVisible) {
        const currentLockState = result.data.currentLockState;
        pageDetails.isLockStateVisible = true;
        pageDetails.lockStateDetail = await pwdResetUtil.getLockStateDetail(currentLockState, helpers);
        if (currentLockState === pwdResetUtil.uiConstants.RETRIEVING_LOCK_STATE) {
            startLockStatePolling();
        } else if (currentLockState === pwdResetUtil.uiConstants.USER_ACCOUNT_NOT_LOCKED) {
            pageDetails.isAccountUnlockApplicable = false;
        }
    }

    api.setState("pageDetails", pageDetails);
    api.setState("pollingInfo", pollingInfo);


    if (isProcessSupportReset && isCredStoreAcceptPassword && !isAutoGeneratedPassword) {
        const passwordStrengthMeterState = { ...api.state.passwordStrengthMeterState
        };
        passwordStrengthMeterState.isHidden = !result.passwordStrength.isPasswordStrengthEnabled;
        api.setState("passwordStrengthMeterState", passwordStrengthMeterState);
        api.setState("passwordPolicyRules", result.passwordPolicy.passwordPolicyRuleHints);
    }
    
    api.emit("PWD_RESET_UIB#HANDLE_LOADING_FROM_RESET_PAGE", {
        "isLoading": false
    });

    function startLockStatePolling() {
        let timeElapsed = 0;
        const refreshRate = pollingInfo.refreshRate;
        const timeOut = pollingInfo.timeOut;
        const intervalId = helpers.timing.setInterval(() => {
            timeElapsed += refreshRate;
            if (timeElapsed < timeOut) {
                api.data.get_pwd_reset_user_lock_state.refresh();
            } else {
                helpers.timing.clearInterval(intervalId);
                api.emit("PWD_RESET_UIB#HANDLE_LOCK_STATE_POLLING_TIMEOUT", {});
            }
        }, refreshRate);
        api.setState("lockStatePollingIntervalId", intervalId);
    }
}
