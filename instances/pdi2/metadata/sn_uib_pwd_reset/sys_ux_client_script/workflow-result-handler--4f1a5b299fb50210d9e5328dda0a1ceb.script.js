/**
 * @param {params} params
 * @param {api} params.api
 * @param {any} params.event
 * @param {any} params.imports
 * @param {ApiHelpers} params.helpers
 */
async function handler({
    api,
    event,
    helpers,
    imports
}) {
    const pwdResetUtil = imports["sn_uib_pwd_reset.PwdResetUxfClientUtil"]();
    const pageDetails = api.state.pageDetails;
    const result = event.payload.data.output;
    if (!result.isValid) {
        api.emit("PWD_RESET_UIB#SHOW_ERROR_PAGE_FROM_RESET", {
            "errorPageObj": {
                "actions": {
                    "restart": {
                        "isHidden": false,
                        "variant": "primary"
                    }
                },
                "heading": await pwdResetUtil.getTranslation(helpers, "Oops! Something went wrong."),
                "icon": "error",
                "subHeading": result.errorMessage
            }
        });
        return;
    }
    if (result.isSuccessful) {
        pwdResetUtil.navigateToResetSuccess(api, helpers);
    } else if (!pageDetails.isAutoGeneratedPassword && result.canRetry) {
        pwdResetUtil.resetManualPWDFlowOnServerSideFailure(api, helpers);
        api.setState("isResetButtonDisabled", false);
    } else {
        api.emit("PWD_RESET_UIB#SHOW_ERROR_PAGE_FROM_RESET", {
            "errorPageObj": {
                "actions": {
                    "restart": {
                        "isHidden": false,
                        "variant": "primary"
                    }
                },
                "content": "",
                "heading": result.message,
                "icon": "error",
                "subHeading": ""
            }
        });
    }
}
