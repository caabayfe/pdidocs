/**
 * @param {params} params
 * @param {api} params.api
 * @param {any} params.event
 * @param {any} params.imports
 * @param {ApiHelpers} params.helpers
 */
async function handler({
    api,
    event,
    helpers,
    imports
}) {
    const pwdResetUtil = imports["sn_uib_pwd_reset.PwdResetUxfClientUtil"]();
    const pageDetails = api.state.pageDetails;
    const result = { ...event.payload.data.output
    };
    api.setState("workflowDetails", result);
    if (!result.isValid) {
        api.emit("PWD_RESET_UIB#SHOW_ERROR_PAGE_FROM_RESET", {
            "errorPageObj": {
                "actions": {
                    "restart": {
                        "isHidden": false,
                        "variant": "primary"
                    }
                },
                "heading": await pwdResetUtil.getTranslation(helpers, "Oops! Something went wrong."),
                "icon": "error",
                "subHeading": result.errorMessage
            }
        });
        return;
    }
    let validationResponse = result.validationResponse;
    if (validationResponse && !validationResponse.isPwdValid) {
        const inputNewPassword = { ...api.state.inputNewPassword
        };
        inputNewPassword.fieldMessage = {
            "isInvalid": true,
            "value": [{
                "content": validationResponse.errorMessage,
                "icon": pwdResetUtil.uiConstants.CIRCLE_EXCLAMATION_OUTLINE_ICON,
                "status": pwdResetUtil.uiConstants.CRITICAL
            }]
        };
        api.setState("inputNewPassword", inputNewPassword);
        api.setState("isResetButtonDisabled", false);
        return;
    }
    let flowResponse = result.flowResponse;
    if (flowResponse.isFlow && (flowResponse.resetStatus === 'success')) {
        pwdResetUtil.navigateToResetSuccess(api, helpers);
    } else if (!pageDetails.isAutoGeneratedPassword && flowResponse.canRetry) {
        pwdResetUtil.resetManualPWDFlowOnServerSideFailure(api, helpers, result);
        api.setState("isResetButtonDisabled", false);
    } else if (!flowResponse.isFlow && flowResponse.resetStatus === 'success') {
        startResetWorkflowPolling();
    } else {
        api.emit("PWD_RESET_UIB#SHOW_ERROR_PAGE_FROM_RESET", {
            "errorPageObj": {
                "actions": {
                    "restart": {
                        "isHidden": false,
                        "variant": "primary"
                    }
                },
                "content": "",
                "heading": flowResponse.message,
                "icon": "error",
                "subHeading": ""
            }
        });
    }

    function startResetWorkflowPolling() {
        let timeElapsed = 0;
        const refreshRate = api.state.pollingInfo.refreshRate;
        const timeOut = api.state.pollingInfo.timeOut;
        const intervalId = helpers.timing.setInterval(() => {
            timeElapsed += refreshRate;
            if (timeElapsed < timeOut) {
                api.data.get_pwd_reset_workflow_progress.execute({
                    token: api.state.token,
                    contextId: flowResponse.contextId
                });
            } else {
                helpers.timing.clearInterval(intervalId);
                api.emit("PWD_RESET_UIB#HANDLE_RESET_WORKFLOW_POLLING_TIMEOUT", {});
            }
        }, refreshRate);
        api.setState("resetStatePollingIntervalId", intervalId);
    }
}
