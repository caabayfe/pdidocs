var PwdResetUXFResetProcessor = Class.create();
PwdResetUXFResetProcessor.prototype = {
    POLLING_RATE_PROPERTY: "password_reset.wf.refresh_rate",
    POLLING_TIMEOUT_PROPERTY: "password_reset.wf.timeout",
    DEFAULT_POLLING_RATE: 500,
    DEFAULT_POLLING_TIMEOUT: 90000,
    RETRIEVING_LOCK_STATE: "0",
    CRED_STORE_ACCEPT_PASSWORD: 0,
    WORKFLOW_CONTEXT_FINISHED_STATE: "finished",
    ACCOUNT_STATE_LOCKED: "1",

    initialize: function() {
        this.userRequestDetails = new global.PwdCommonUtils().getUserRequestDetails();
        this.pwdResetStageHandler = new global.PwdResetStageHandler();
    },

    CONSTANTS: {
        PWD_RESET_REQUEST: "pwd_reset_request",
        PROCESS: "process",
        LOCK_STATE: "lock_state",
        SYS_USER: "sys_user",
        USER_NAME: "user_name"
    },

    getPageInfo: function(token) {
        var result = this._getRequestValidationStatus(token);
        if (!result.isValid) {
            return result;
        }
        var isAutoGeneratedPassword;
        var isProcessSupportUnlock;
        var isProcessSupportReset;
        var currentLockState;
        var isCredStoreAcceptPassword;
        var isLockStateSubflowMapped;
        var requestGr = new GlideRecord(this.CONSTANTS.PWD_RESET_REQUEST);
        var isDisplayPassword;
        var isSendEmail;
        if (requestGr.get(this.userRequestDetails.requestId)) {
            isAutoGeneratedPassword = !!requestGr.process.auto_gen_password;
            isProcessSupportUnlock = !!requestGr.process.unlock_account;
            isProcessSupportReset = !!requestGr.process.reset;
            currentLockState = requestGr.getValue(this.CONSTANTS.LOCK_STATE);

            //if user's account is locked and account unlock is not supported then redirect to error page
            if (!isProcessSupportUnlock && currentLockState === this.ACCOUNT_STATE_LOCKED) {
                result.isValid = false;
                result.processName = requestGr.process.label + "";
                result.errorMessage = "unlock_not_support_but_account_locked";
                return result;
            }

            isDisplayPassword = !!requestGr.process.display_password;
            isSendEmail = !!requestGr.process.send_email;
            var credStoreType = requestGr.process.cred_store.type;
            isCredStoreAcceptPassword = Boolean(credStoreType.use_flow) !== true || parseInt(credStoreType.password_delivery_mechanism) === this.CRED_STORE_ACCEPT_PASSWORD;
            isLockStateSubflowMapped = Boolean(credStoreType.use_flow) !== true || !gs.nil(credStoreType.get_lock_state_flow);
        } else {
            result.isValid = false;
            result.errorMessage = gs.getMessage("Unable to fetch Password Reset request.");
            return result;
        }
        result = this._getPageInitializeSuccessTemplate();
        var pollingRate = gs.getProperty(this.POLLING_RATE_PROPERTY);
        var pollingTimeOut = gs.getProperty(this.POLLING_TIMEOUT_PROPERTY);
        result.data.isAutoGeneratedPassword = isAutoGeneratedPassword;
        result.data.isProcessSupportUnlock = isProcessSupportUnlock;
        result.data.isCredStoreAcceptPassword = isCredStoreAcceptPassword;
        result.data.isProcessSupportReset = isProcessSupportReset;
        result.data.isDisplayPassword = isDisplayPassword;
        result.data.isSendEmail = isSendEmail;
        result.data.currentLockState = currentLockState;
        result.data.isLockStateSubflowMapped = isLockStateSubflowMapped;
        result.data.pollingInfo.refreshRate = gs.nil(pollingRate) || isNaN(pollingRate) ? this.DEFAULT_POLLING_RATE : parseInt(pollingRate);
        result.data.pollingInfo.timeOut = gs.nil(pollingTimeOut) || isNaN(pollingTimeOut) ? this.DEFAULT_POLLING_TIMEOUT : parseInt(pollingTimeOut);

        if (isProcessSupportReset && isCredStoreAcceptPassword && !isAutoGeneratedPassword) {
            var isPasswordPolicyEnabled = Boolean(requestGr.process.cred_store.enable_password_policy);
            var isPasswordStrengthEnabled = Boolean(requestGr.process.cred_store.enable_password_strength);
            result.passwordPolicy.isPasswordPolicyEnabled = isPasswordPolicyEnabled;
            result.passwordStrength.isPasswordStrengthEnabled = isPasswordStrengthEnabled;
            var processID = requestGr.getValue(this.CONSTANTS.PROCESS);

            if (isPasswordPolicyEnabled) {
                if (isPasswordStrengthEnabled) {
                    var policyID = requestGr.process.cred_store.password_policy + "";
                    result.passwordStrength.strengthRuleParams = this.pwdResetStageHandler.getPasswordStrengthScriptParams(policyID);
                }
                var passwordPolicyRuleHints = JSON.parse(
                    this.pwdResetStageHandler.getPasswordPolicyRuleHints(processID)
                );
                passwordPolicyRuleHints.rulesWithRegex.forEach(function(rule) {
                    rule.isValid = false;
                    rule.isInitialIconHidden = false;
                    rule.isValidIconHidden = true;
                    rule.isInvalidIconHidden = true;
                });
                result.passwordPolicy.passwordPolicyRuleHints = passwordPolicyRuleHints;
            }
        }
        result.token = new global.PwdCommonUtils().generateCSRFToken();
        return result;
    },

    getLockStateFromRequest: function(token) {
        var result = this._getRequestValidationStatus(token);
        if (!result.isValid) {
            return result;
        }
        var lockState = this.RETRIEVING_LOCK_STATE;
        var requestGr = new GlideRecord(this.CONSTANTS.PWD_RESET_REQUEST);
        if (requestGr.get(this.userRequestDetails.requestId)) {
            lockState = requestGr.getValue(this.CONSTANTS.LOCK_STATE);
        } else {
            result.errorMessage = gs.getMessage("Unable to fetch Password Reset request.");
            result.isValid = false;
            return result;
        }

        var isProcessSupportUnlock = !!requestGr.process.unlock_account;

        //if user's account is locked and account unlock is not supported then redirect to error page
        if (!isProcessSupportUnlock && lockState === this.ACCOUNT_STATE_LOCKED) {
            result.isValid = false;
            result.processName = requestGr.process.label + "";
            result.errorMessage = "unlock_not_support_but_account_locked";
            return result;
        }

        result.isValid = true;
        result.lockState = lockState;
        return result;
    },

    unlockAccount: function(token) {
        var result = this._getErrorTemplate();
        var securityResponse = new sn_uib_pwd_reset.PwdResetUXFUtil().getSecurityValidationResult(token);
        if (!securityResponse.isValid) {
            result.errorMessage = securityResponse.errorMessage;
            return result;
        }

        var userId = this.userRequestDetails.userId;
        var requestId = this.userRequestDetails.requestId;

        var resp = new global.PwdResetStageHandler().startUnlockFlow(requestId, userId);

        var isUseFlow = this._isFlow(requestId);

        if (typeof resp === 'string' && resp.includes('failure')) {
            result.errorMessage = gs.getMessage("Error while unlocking the account. Please try again.");
            return result;
        } else {
            if (isUseFlow) {
                result = this._getUnlockSuccessTemplate();
                result.token = new global.PwdCommonUtils().generateCSRFToken();
                return result;
            } else { //workflow case, wfContextId will be used during polling
                result = this._getUnlockSuccessTemplate();
                result.data.isFlow = false;
                result.data.wfContextId = resp + "";
                return result;
            }
        }
    },

    getAccountUnlockStatusOnPolling: function(token, contextID) {
        var result = this._getErrorTemplate();
        var securityResponse = new sn_uib_pwd_reset.PwdResetUXFUtil().getSecurityValidationResult(token);
        if (!securityResponse.isValid) {
            result.errorMessage = securityResponse.errorMessage;
            return result;
        }

        result = this._getUnlockPollingSuccessTemplate();

        var ctxGr = new GlideRecord('wf_context');

        if (ctxGr.get(contextID)) {
            result.data.result = ctxGr.getValue('result');
            result.data.state = ctxGr.getValue('state');

            if (result.data.state === this.WORKFLOW_CONTEXT_FINISHED_STATE)
                result.token = new global.PwdCommonUtils().generateCSRFToken();
        }
        return result;
    },

    startResetFlow: function(token, password) {
        var result = this._getRequestValidationStatus(token);
        if (!result.isValid) {
            return result;
        }
        var requestId = this.userRequestDetails.requestId;
        var processId = '';
        var isFlow = false;
        var credStoreType = null;
        var isAutoGenPassword = false;
        var isCredStoreAcceptPassword = false;
        var requestGr = new GlideRecord(this.CONSTANTS.PWD_RESET_REQUEST);
        var pwdWfRequestProcessor = new global.PwdWFRequestProcessor();
        if (requestGr.get(requestId)) {
            processId = requestGr.process;
            isFlow = (requestGr.process.cred_store.type.use_flow + "") === "true";
            isAutoGenPassword = Boolean(requestGr.process.auto_gen_password);
            credStoreType = requestGr.process.cred_store.type;
            isCredStoreAcceptPassword = Boolean(credStoreType.use_flow) !== true || parseInt(credStoreType.password_delivery_mechanism) === this.CRED_STORE_ACCEPT_PASSWORD;
        }
        if (!isAutoGenPassword && isCredStoreAcceptPassword) {
            var user = this.userRequestDetails.userId;
            var userGR = new GlideRecord(this.CONSTANTS.SYS_USER);
            if (userGR.get(this.userRequestDetails.userId)) {
                user = userGR.getValue(this.CONSTANTS.USER_NAME);
            }
            var validationResponse = pwdWfRequestProcessor.validatePassword(processId, password, user);
            validationResponse = JSON.parse(validationResponse);
            result.validationResponse = validationResponse;
            if (!validationResponse.isPwdValid)
                return result;
        }
        var flowResponse = pwdWfRequestProcessor.startWorkflow(requestId, password, false);
        var response = this._getResetSuccessTemplate();
        response.isFlow = isFlow;
        response.resetStatus = flowResponse.status;
        response.message = flowResponse.message;
        response.contextId = response.isFlow === true ? '' : flowResponse.value;
        result.flowResponse = response;
        if (flowResponse.status.match(/failure/i)) {
            // retry option for non fatal failure for flow
            if (response.isFlow && response.message === "non_fatal_failure") {
                result.flowResponse.canRetry = true;
            }
            return result;
        }
        if (response.isFlow) {
            this._runPostProcessorScript(requestId, processId, true);
        }
        return result;
    },

    checkWorkflowProgress: function(token, contextId) {
        var result = new sn_uib_pwd_reset.PwdResetUXFUtil().getSecurityValidationResult(token);
        if (!result.isValid)
            return result;
        result.workflowStatus = this._getWorkflowStatus(contextId);
        return result;
    },

    checkWorkflowResult: function(token, contextId) {
        var result = new sn_uib_pwd_reset.PwdResetUXFUtil().getSecurityValidationResult(token);
        if (!result.isValid)
            return result;
        result = {
            isValid: true,
            isSuccessful: false,
            canRetry: false,
            message: ''
        };
        if (!contextId) {
            result.message = gs.getMessage("Password reset request failed.");
            return result;
        }
        var workflowResult = new global.PwdResetStageHandler().getWFData(contextId);
        var areAllActivitiesSuccessful = true;
        var history = workflowResult.history;
        var allActivitiesObj = [];

        // Grab all the activities in the workflow and build an array of objects
        for (var index = 0; index < history.length; index++) {
            var activityObj = {};
            var currentHistoryObj = history[index];
            activityObj.name = currentHistoryObj.activity.name;
            activityObj.index = currentHistoryObj.activity_index;
            activityObj.result = currentHistoryObj.activity_result == undefined ? "" : currentHistoryObj.activity_result;
            activityObj.faultDescription = currentHistoryObj.fault_description == undefined ? "" : currentHistoryObj.fault_description;
            allActivitiesObj.push(activityObj);
        }
        // Iterate through activity history list to find the first error
        allActivitiesObj.sort(function(a, b) {
            return b.index - a.index;
        });
        var failingActivityObj = {};
        for (var activityObject in allActivitiesObj) {
            var currentActivityObj = allActivitiesObj[activityObject];

            if (currentActivityObj.result.match(/failure/i)) {
                areAllActivitiesSuccessful = false;

                // Check if faultDescription is an json object. If so, this was created via SNC.PwdWorkflowManager().creatError().
                try {
                    failingActivityObj = global.JSON.parse(currentActivityObj.faultDescription);

                } catch (e) {
                    //The faultDescription was created manually, and not via new SNC.PwdWorkflowManager().getErrorJSONString(...)
                    failingActivityObj.message = currentActivityObj.faultDescription;
                    failingActivityObj.isFatal = true;
                }
                break;
            }
        }

        if (!areAllActivitiesSuccessful) {
            result.isSuccessful = false;
            result.message = failingActivityObj.message || gs.getMessage("Password reset request failed.");
        } else {
            result.isSuccessful = true;
        }

        var requestId = this.userRequestDetails.requestId;
        var processId = '';
        var requestGr = new GlideRecord("pwd_reset_request");
        if (requestGr.get(requestId)) {
            processId = requestGr.process;
        }

        if (!result.isSuccessful && !failingActivityObj.isFatal) {
            //This is only used for AD cred store
            var isMaxAttemptsReached = new global.PwdResetStageHandler().isMaxAttemptsReached(requestId);
            if (isMaxAttemptsReached) {
                failingActivityObj.isFatal = true;
                result.isSuccessful = false;
                result.message = gs.getMessage("Max Failure Attempts Reached");
            } else {
                result.message = failingActivityObj.message || gs.getMessage("Non fatal failure");
                result.canRetry = true;
                return result;
            }
        }
        this._runPostProcessorScript(requestId, processId, result.isSuccessful);
        return result;
    },

    _getWorkflowStatus: function(contextId) {
        var state = 'failure';
        var gr = new GlideRecord('wf_context');
        if (gr.get(contextId)) {
            state = gr.getValue('state');
        }
        return state;
    },

    _runPostProcessorScript: function(requestId, processId, workflowStatus) {
        return new global.PwdResetStageHandler().runPostProcessorScript(requestId, processId, workflowStatus);
    },

    _getResetSuccessTemplate: function() {
        return {
            resetStatus: '',
            message: '',
            contextId: '',
            canRetry: false,
            isFlow: false,
        };
    },

    _isFlow: function(requestId) {
        var request = new GlideRecord('pwd_reset_request');
        request.get(requestId);
        return (request.process.cred_store.type.use_flow + "") === "true";
    },

    _getRequestValidationStatus: function(token) {
        var result = this._getErrorTemplate();
        var securityResponse = new sn_uib_pwd_reset.PwdResetUXFUtil().getSecurityValidationResult(token);
        if (!securityResponse.isValid) {
            result.errorMessage = securityResponse.errorMessage;
            return result;
        }
        if (!this.pwdResetStageHandler.isRequestVerified(this.userRequestDetails.requestId)) {
            result.errorMessage = gs.getMessage("Password reset request is not verified.");
            return result;
        }
        result.isValid = true;
        return result;
    },

    _getErrorTemplate: function() {
        return {
            isValid: false,
            errorMessage: ""
        };
    },

    _getUnlockSuccessTemplate: function() {
        return {
            isValid: true,
            token: "",
            data: {
                isFlow: true,
                wfContextId: ""
            }
        };
    },

    _getUnlockPollingSuccessTemplate: function() {
        return {
            isValid: true,
            token: "",
            data: {
                result: 'failure',
                state: 'executing'
            }
        };
    },

    _getPageInitializeSuccessTemplate: function() {
        return {
            isValid: true,
            token: "",
            data: {
                isProcessSupportReset: true,
                isProcessSupportUnlock: true,
                isCredStoreAcceptPassword: true,
                isAutoGeneratedPassword: true,
                isDisplayPassword: false,
                isSendEmail: false,
                isLockStateSubflowMapped: true,
                currentLockState: this.RETRIEVING_LOCK_STATE,
                pollingInfo: {},
                acceptPasswordDetail: null
            },
            passwordPolicy: {
                isPasswordPolicyEnabled: null
            },
            passwordStrength: {
                isPasswordStrengthEnabled: null
            }
        };
    },

    type: 'PwdResetUXFResetProcessor'
};
