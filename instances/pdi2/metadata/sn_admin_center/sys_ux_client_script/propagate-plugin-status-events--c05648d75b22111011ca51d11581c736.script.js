/**
 * @param {params} params
 * @param {api} params.api
 * @param {any} params.event
 * @param {any} params.imports
 * @param {ApiHelpers} params.helpers
 */
function handler({
    api,
    event,
    helpers,
    imports
}) {
    if (event.payload && event.payload.eventName) {
        api.emit('ACE_ACTION_PERFORMED', event.payload);
    }
}
