var GlideGuardedScript = Class.create();
GlideGuardedScript.prototype = {
    initialize: function() {
        this.PROP_PHASE = 'com.glide.script.sandbox.ks.watchdog.phase';
        this.PROP_PHASE_START = 'com.glide.script.sandbox.ks.watchdog.phase.start';
        this.PROP_DURATION_DAYS = 'com.glide.script.sandbox.ks.watchdog.phase.duration.days';
        this.PROP_AUTO_ADVANCE = 'com.glide.script.sandbox.ks.watchdog.auto.advance';
        this.PROP_ENABLED = 'com.glide.script.sandbox.ks.watchdog.enabled';
        this.LOG_PREFIX = 'KS_WATCHDOG: ';
    },

    /** Creates an exemption from an incompatible script record */
    addExemption: function(incompatibleScript, autoGenerated) {
        var exemption = new GlideRecord('sys_gs_exemption');
        exemption.addQuery('normalized_script', incompatibleScript.getValue('normalized_script'));
        exemption.addQuery('authenticated', incompatibleScript.getValue('authenticated'));
        exemption.query();
        var exId;
        var created;
        if (exemption.next()) {
            exId = exemption.getUniqueValue();
            created = false;
        } else {
            var ex = new GlideRecordSecure('sys_gs_exemption');
            ex.initialize();
            ex.setValue('normalized_script', incompatibleScript.getValue('normalized_script'));
            ex.setValue('authenticated', incompatibleScript.getValue('authenticated'));
            ex.setValue('active', true);
            ex.setValue('auto_generated', !!autoGenerated);
            ex.setWorkflow(false);
            exId = ex.insert();
            if (!exId) {
                gs.logWarning('GlideGuardedScript: exemption insert blocked by ACL for script: ' +
                    incompatibleScript.getValue('normalized_script'), 'GlideGuardedScript');
                return null;
            }
			if (autoGenerated) {
				gs.info('GlideGuardedScript: exemption generated automatically ' +
					' for script: ' + incompatibleScript.getValue('normalized_script'));
			} else {
                gs.info('GlideGuardedScript: exemption created by ' + gs.getUserName() +
                    ' for script: ' + incompatibleScript.getValue('normalized_script'));
            }
            created = true;
        }
        var siblings = new GlideRecord('sys_gs_incompatible_scripts');
        siblings.addQuery('normalized_script', incompatibleScript.getValue('normalized_script'));
        siblings.addQuery('authenticated', incompatibleScript.getValue('authenticated'));
        siblings.addNullQuery('exemption');
        siblings.query();
        while (siblings.next()) {
            siblings.setValue('exemption', exId);
            siblings.setWorkflow(false);
            siblings.update();
        }
        return created;
    },

    /**
     * Called by the scheduled job on each run. Checks the current watchdog state
     * and advances the phase if the duration has elapsed.
     */
    runWatchdog: function() {
      var mutex = new GlideMutex('ks_watchdog_transition');
      if (!mutex.get()) {
          gs.info(this.LOG_PREFIX + 'Could not acquire mutex for initialization, will retry next run');
          return;
      }
      try {
          var enabled = gs.getProperty(this.PROP_ENABLED, 'true');
          if (enabled !== 'true') {
              gs.info(this.LOG_PREFIX + 'Watchdog disabled, skipping');
              return;
          }

          var phase = gs.getProperty(this.PROP_PHASE, '0');

          // First run after upgrade: initialize to Phase 1
          if (phase === '0') {
              this._initializeWatchdog('0');
              return;
          }

          // Terminal state
          if (phase === '3') {
              return;
          }

		  // Invalid phase: reset
          if (phase !== '1' && phase !== '2') {
              gs.warn(this.LOG_PREFIX + 'Invalid phase, resetting to 1 - invalid value was ' + phase);
              this._initializeWatchdog(phase);
              return;
          }

          // Kill switch: freeze progression
          var durationDays = parseInt(gs.getProperty(this.PROP_DURATION_DAYS, '14'), 10);
          if (durationDays <= 0) {
              gs.warn(this.LOG_PREFIX + 'Kill switch engaged (duration.days <= 0), phase frozen at ' + phase);
              return;
          }
          if (Number.isNaN(durationDays)) {
              gs.warn(this.LOG_PREFIX + 'Invalid duration.days; phase frozen at ' + phase);
              return;
          }

          // Manual advancement only
          var autoAdvance = gs.getProperty(this.PROP_AUTO_ADVANCE, 'true');
          if (autoAdvance !== 'true') {
            gs.info(this.LOG_PREFIX + 'Auto advance disabled, stopping');
            return;
          }

          // Validate phase.start
          var phaseStart = gs.getProperty(this.PROP_PHASE_START, 'NOT_STARTED');
          var startDate = this._parseStartDate(phaseStart);
          if (!startDate) {
              gs.warn(this.LOG_PREFIX + 'Corrupted phase.start (' + phaseStart + '), resetting to now');
              gs.setProperty(this.PROP_PHASE_START, new GlideDateTime().toString());
              return;
          }

          // Check if duration has elapsed
          var now = new GlideDateTime();
          var elapsed = gs.dateDiff(startDate.toString(), now.toString(), true);
          var elapsedDays = Math.floor(parseInt(elapsed, 10) / 86400);
          if (elapsedDays >= durationDays) {
              this._advancePhase(phase);
          } else {
              gs.info(this.LOG_PREFIX + 'Not enough time has elapsed, not advancing from phase ' + phase +
                      ' since only ' + elapsedDays + ' days elapsed since ' + startDate +
                      ' and the cutoff is at ' + durationDays + ' days');
          }
      } finally {
          mutex.release();
      }
    },

    /**
     * Advances to Phase 2. For use by on-prem administrators via fix script.
     * Does not check auto.advance or duration. Creates exemptions.
     * Can only be called from phase 1.
     */
    advanceToPhase2: function() {
      var enabled = gs.getProperty(this.PROP_ENABLED, 'true');
      if (enabled !== 'true') {
        gs.info(this.LOG_PREFIX + 'Watchdog disabled, not advancing manually because invalid scripts have not been captured');
        return;
      }

      var mutex = new GlideMutex('ks_watchdog_transition');
      if (!mutex.get()) {
        gs.warn(this.LOG_PREFIX + 'Could not acquire mutex for advanceToPhase2');
        return;
      }
      try {
          var phase = gs.getProperty(this.PROP_PHASE, '0');
          if (phase !== '1') {
              gs.warn(this.LOG_PREFIX + 'Cannot advance to Phase 2: current phase is ' + phase);
              return;
          }
          this._advancePhase('1');
      } finally {
          mutex.release();
      }
    },

    /**
     * Advances to Phase 3. For use by on-prem administrators via fix script.
     * Does not check auto.advance or duration. Creates exemptions.
     * Can only be called from phase 2.
     */
    advanceToPhase3: function() {
      var enabled = gs.getProperty(this.PROP_ENABLED, 'true');
      if (enabled !== 'true') {
        gs.info(this.LOG_PREFIX + 'Watchdog disabled, not advancing manually because invalid scripts have not been captured');
        return;
      }

      var mutex = new GlideMutex('ks_watchdog_transition');
      if (!mutex.get()) {
        gs.warn(this.LOG_PREFIX + 'Could not acquire mutex for advanceToPhase3');
        return;
      }
      try {
          var phase = gs.getProperty(this.PROP_PHASE, '0');
          if (phase !== '2') {
              gs.warn(this.LOG_PREFIX + 'Cannot advance to Phase 3: current phase is ' + phase);
              return;
          }
          this._advancePhase('2');
      } finally {
          mutex.release();
      }
    },

    /**
     * Resets to Phase 1. For use by administrators as a recovery action.
     * Doesn't modify auto.advance. Doesn't modify exemptions.
     */
    resetToPhase1: function() {
		// Allow even if kill switch is disabled, because it is possible we'll end up in this situation:
        // "we're in phase 3, find a bug, turn off kill switch, install new version with bug fix, reset to 1"

        var mutex = new GlideMutex('ks_watchdog_transition');
        if (!mutex.get()) {
            gs.warn(this.LOG_PREFIX + 'Could not acquire mutex for resetToPhase1');
            return;
        }
        try {
            var fromPhase = gs.getProperty(this.PROP_PHASE, '0');

            gs.setProperty(this.PROP_PHASE, '1');
            gs.setProperty(this.PROP_PHASE_START, new GlideDateTime().toString());

            gs.info(this.LOG_PREFIX + 'Reset to Phase 1');
            gs.eventQueue('ks.watchdog.phase.transition', null, fromPhase, '1');
        } finally {
            mutex.release();
        }
    },

    // ---- Private methods ----

    _initializeWatchdog: function(oldPhase) {
        gs.setProperty(this.PROP_PHASE, '1');
        gs.setProperty(this.PROP_PHASE_START, new GlideDateTime().toString());

        // Detect on-prem and disable auto-advance
        if (this._isOnPrem()) {
            gs.setProperty(this.PROP_AUTO_ADVANCE, 'false');
            gs.info(this.LOG_PREFIX + 'Initialized to Phase 1 (on-prem detected, auto.advance=false)');
        } else {
            gs.setProperty(this.PROP_AUTO_ADVANCE, 'true');
            gs.info(this.LOG_PREFIX + 'Initialized to Phase 1');
        }

        gs.eventQueue('ks.watchdog.phase.transition', null, oldPhase, '1');
    },

    _advancePhase: function(currentPhase) {
        var nextPhase = String(parseInt(currentPhase, 10) + 1);

        // Create exemptions for incompatible scripts
        var exemptionCount = this._createExemptions();

        gs.setProperty(this.PROP_PHASE, nextPhase);
        gs.setProperty(this.PROP_PHASE_START, new GlideDateTime().toString());

        gs.info(this.LOG_PREFIX + 'Transitioned from Phase ' + currentPhase + ' to Phase ' + nextPhase
            + ' (' + exemptionCount + ' exemptions created)');
        gs.eventQueue('ks.watchdog.phase.transition', null, currentPhase, nextPhase);
    },

    _createExemptions: function() {
        var count = 0;
        var gr = new GlideRecord('sys_gs_incompatible_scripts');
        gr.addNullQuery('exemption');
        gr.addQuery('authenticated', 'true');
        gr.query();

        while (gr.next()) {
            if (this.addExemption(gr, true)) {
                count++;
            }
        }
        return count;
    },

    _isOnPrem: function() {
        var selfHosted = gs.getProperty('glide.installation.self_hosted', 'false');
        return selfHosted === 'true';
    },

    _parseStartDate: function(dateStr) {
        if (!dateStr || dateStr === 'NOT_STARTED' || dateStr === 'always') {
            return null;
        }
        var gdt = new GlideDateTime();
        gdt.setValue(dateStr);
        if (!gdt.isValid()) {
            return null;
        }
        return gdt;
    },

    type: 'GlideGuardedScript'
};
