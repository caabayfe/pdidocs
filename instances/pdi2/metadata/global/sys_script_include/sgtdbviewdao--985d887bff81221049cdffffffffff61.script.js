var SGTDBViewDAO = Class.create();
SGTDBViewDAO.prototype = {
    initialize: function() {
        this.SGT_SCAN_RESULT = "sgt_scan_result";
        this.SYS_USER_GRMEMBER = "sys_user_grmember";
        this.SYS_DB_VIEW = "sys_db_view";
        this.SYS_DB_VIEW_TABLE = "sys_db_view_table";
        this.SYS_DB_VIEW_TABLE_FIELD = "sys_db_view_table_field";

        this.DB_VIEW_NAME_PREFIX = "scan_results_grmember_";
        this.DB_VIEW_DESCRIPTION = "Generated by scripting governance tool";
        this.DB_VIEW_LABEL = "Users that have not scripted";

        this.NAME = "name";
        this.LABEL = "label";
        this.DESCRIPTION = "description";
        this.TABLE = "table";
        this.FIELD = "field";
        this.VARIABLE_PREFIX = "variable_prefix";
        this.VIEW = "view";
        this.VIEW_TABLE = "view_table";
        this.ORDER = "order";
        this.LEFT_JOIN = "left_join";
        this.WHERE_CLAUSE = "where_clause";
        this.USER = "user";
        this.GROUP = "group";
        this.SCAN = "scan";
        this.SYS_CREATED_ON = "sys_created_on";
        this.LAST_SCRIPTED = "last_scripted";
        this.KEEP = 'keep';

        this.SCAN_RESULT_ALIAS = "ssr";
        this.GRMEMBER_ALIAS = "grmember";

        this.COUNT = "COUNT";
        this.STARTSWITH = "STARTSWITH";
    },

    getOrCreateNonScriptedUsersDBView: function(scanId) {
        var lastThreeScans = new global.SGTScanHistoryDAO().getLastNCompletedScans(3);
        if (!lastThreeScans.includes(scanId))
            return "";

        this._deleteDBViewsIfRequired(lastThreeScans);

        var dbViewName = this.DB_VIEW_NAME_PREFIX + scanId;
        if (this._doesDBViewExist(dbViewName))
            return dbViewName;

        this._createDBViewAndViewTableRecords(dbViewName, scanId);
        return dbViewName;
    },

    _doesDBViewExist: function(dbViewName) {
        var dbViewGA = new GlideAggregate(this.SYS_DB_VIEW);
        dbViewGA.addAggregate(this.COUNT);
        dbViewGA.addQuery(this.NAME, dbViewName);
        dbViewGA.query();
        dbViewGA.next();
        return dbViewGA.getAggregate(this.COUNT) == 1;
    },

    _deleteDBViewsIfRequired: function(lastThreeScans) {
        var dbViewGR = new GlideRecord(this.SYS_DB_VIEW);
        dbViewGR.addQuery(this.NAME, this.STARTSWITH, this.DB_VIEW_NAME_PREFIX);
        dbViewGR.query();
        while (dbViewGR.next()) {
            var scanIdForView = dbViewGR.getValue(this.NAME).split(this.DB_VIEW_NAME_PREFIX)[1];
            if (!lastThreeScans.includes(scanIdForView))
                dbViewGR.deleteRecord();
        }

    },

    _createDBViewAndViewTableRecords: function(dbViewName, scanId) {
        var dbViewSysId = this._createDBView(dbViewName);
        var grMemberViewTableSysId = this._createGRMemberViewTable(dbViewSysId);
        var scanResultViewTableSysId = this._createScanResultsViewTable(dbViewSysId, scanId);
        this._createGRMemberViewTableFields(grMemberViewTableSysId);
        this._createScanResultsViewTableFields(scanResultViewTableSysId);
    },

    _createDBView: function(dbViewName) {
        var dbViewGR = new GlideRecord(this.SYS_DB_VIEW);
        dbViewGR.setValue(this.NAME, dbViewName);
        dbViewGR.setValue(this.DESCRIPTION, this.DB_VIEW_DESCRIPTION);
        dbViewGR.setValue(this.LABEL, this.DB_VIEW_LABEL);
        dbViewGR.setWorkflow(false);
        return dbViewGR.insert();
    },

    _createGRMemberViewTable: function(dbViewSysId) {
        var dbViewGR = new GlideRecord(this.SYS_DB_VIEW_TABLE);
        dbViewGR.setValue(this.TABLE, this.SYS_USER_GRMEMBER);
        dbViewGR.setValue(this.VARIABLE_PREFIX, this.GRMEMBER_ALIAS);
        dbViewGR.setValue(this.VIEW, dbViewSysId);
        dbViewGR.setValue(this.ORDER, 100);
        dbViewGR.setWorkflow(false);
        return dbViewGR.insert();
    },

    _createScanResultsViewTable: function(dbViewSysId, scanId) {
        var dbViewGR = new GlideRecord(this.SYS_DB_VIEW_TABLE);
        dbViewGR.setValue(this.TABLE, this.SGT_SCAN_RESULT);
        dbViewGR.setValue(this.VARIABLE_PREFIX, this.SCAN_RESULT_ALIAS);
        dbViewGR.setValue(this.VIEW, dbViewSysId);
        dbViewGR.setValue(this.LEFT_JOIN, true);
        dbViewGR.setValue(this.ORDER, 200);
        dbViewGR.setValue(this.WHERE_CLAUSE, `ssr_scan = '${scanId}' && grmember_user = ssr_user`);
        dbViewGR.setWorkflow(false);
        return dbViewGR.insert();
    },

    _createScanResultsViewTableFields: function(scanResultViewTableSysId) {
        var scanResultsViewTableFields = [this.SCAN, this.USER, this.LAST_SCRIPTED, this.KEEP];
        scanResultsViewTableFields.forEach(field => {
            var dbViewTableFieldGR = new GlideRecord(this.SYS_DB_VIEW_TABLE_FIELD);
            dbViewTableFieldGR.setValue(this.FIELD, field);
            dbViewTableFieldGR.setValue(this.TABLE, this.SGT_SCAN_RESULT);
            dbViewTableFieldGR.setValue(this.VIEW_TABLE, scanResultViewTableSysId);
            dbViewTableFieldGR.insert();
        });
    },

    _createGRMemberViewTableFields: function(grMemberViewTableSysId) {
        var grMemberViewTableFields = [this.USER, this.GROUP, this.SYS_CREATED_ON];
        grMemberViewTableFields.forEach(field => {
            var dbViewTableFieldGR = new GlideRecord(this.SYS_DB_VIEW_TABLE_FIELD);
            dbViewTableFieldGR.setValue(this.FIELD, field);
            dbViewTableFieldGR.setValue(this.TABLE, this.SYS_USER_GRMEMBER);
            dbViewTableFieldGR.setValue(this.VIEW_TABLE, grMemberViewTableSysId);
            dbViewTableFieldGR.insert();
        });
    },

    type: 'SGTDBViewDAO'
};
