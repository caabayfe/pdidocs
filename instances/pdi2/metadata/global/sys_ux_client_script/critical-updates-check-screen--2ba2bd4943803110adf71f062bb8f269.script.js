/**
 * @param {params} params
 * @param {api} params.api
 * @param {any} params.event
 * @param {any} params.imports
 * @param {ApiHelpers} params.helpers
 */
function handler({
    api,
    event,
    helpers,
    imports
}) {
    if (event.payload.name === "screen" && event.payload.value.isActive) {
        api.data.critical_updates_timeline.refresh();
    }
}
