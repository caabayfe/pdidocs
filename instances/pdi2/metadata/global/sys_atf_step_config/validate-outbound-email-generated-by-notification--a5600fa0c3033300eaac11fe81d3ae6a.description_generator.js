(function generateDescription(step) {
    var descriptionGenerator = new ATFStepDescriptionGenerator();
    var description;
    var conditions = step.inputs.conditions;
    if (conditions == '' || conditions == '^EQ')
        description = gs.getMessage("Validate that an email was generated by notification '{0}'",
                                    [step.inputs.source_notification.getDisplayValue()]);
    else
        description = gs.getMessage("Validate that an email was generated by notification '{0}' matching query:\n{1}",
                                    [step.inputs.source_notification.getDisplayValue(),
                                     descriptionGenerator.getConditionDescription('sys_email', step.inputs.conditions)]);
    description += descriptionGenerator.getTimeoutDescription(step.timeout);
    return description;

})(step);
