function onLoad() {

    // Return if new sitemap config record is being created 
    if (g_form.isNewRecord())
        return;

    var sitemapConfigId = g_form.getUniqueValue();

    // Call script include, 'SitemapAttachment' with param - sitemapConfigId to get sitemap attachment details
    var ga = new GlideAjax('SitemapAttachment');
    ga.addParam('sysparm_name', 'getSitemapXMLDetails');
    ga.addParam('sysparm_sitemap_config_id', sitemapConfigId);

    ga.getXMLAnswer(sitemapXMLDetails);

}

// callback function to get the response from the script include -  sitemap attachment
function sitemapXMLDetails(response) {
	var result = JSON.parse(response);
    if (result != null) {
        if (result.created_by != '' && result.created_on != '') {
            // set url to show messages related to sitemap generation 
            var url = '<a href="syslog_app_scope_list.do?sysparm_query=messageLIKEsitemap&sysparm_first_row=1&sysparm_view=">here</a>';
            var info_message = nowapi.g_i18n.format("{3} {0} {4} {1}. {5} {2} {6}.", result.created_by, result.created_on, url, getMessage('Sitemap XML generated by'), getMessage('on'), getMessage('Click'), getMessage('for logs'));
            g_form.addInfoMessage(info_message);
        }
    }

}
