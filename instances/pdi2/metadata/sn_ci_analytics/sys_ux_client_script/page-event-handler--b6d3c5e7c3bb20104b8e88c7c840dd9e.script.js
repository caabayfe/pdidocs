/**
 * @param {params} params
 * @param {api} params.api
 * @param {any} params.event
 * @param {any} params.imports
 */
function handler({
    api,
    event,
    helpers,
    imports
}) {
    const {
        listType,
        encodedQuery
    } = api.context.props;
    const {
        comparisonModel,
        vaEncodedQueryGeneratedByCB
    } = api.state;
    const {
        output
    } = api.data.get_filters_list;

    function _isSelectedFilterIdValid(selectedFilterId) {
        if (output) {
            return output.findIndex(filter => filter.id === selectedFilterId) >= 0;
        }
        return false;
    }

    function clearFilter() {
        api.setState('comparisonModel', [{
            'comparisonType': 'NEW_QUERY',
            'field': '',
            'operator': '',
            'conditionValue': '',
            'tableName': PAGE_CONSTANTS.comparison_model_table,
            'hideAndButton': false,
            'hideOrButton': false,
            'children': []
        }]);
        api.setState('isFilterLoading', true);
        const filterId = 'all';
        api.setState('selectedFilterId', filterId);
        api.data.load_filter.execute({
            filterId,
            listType
        });
        return true;
    }
    const PAGE_CONSTANTS = {
        'event_ready': 'MACROPONENT_READY',
        'event_prop_changed': 'MACROPONENT_PROPERTY_CHANGED',
        'encoded_query_prop': 'encodedQuery',
        'comparison_model_table': listType == 'conversation' ? 'va_conversations' : 'va_users'
    };
    //TODO: Convert load_filter data broker to 'non-mutable'.
    
    //Case a: if encoded-query is empty
    if (!encodedQuery) {
        return clearFilter();
    }

    //Case b: if encoded-query exists
    //Case b.a: if encoded-query contains sys_id
    const matches = (/^sys_id:(.*$)/g).exec(encodedQuery);
    if (matches) {
        const filterId = matches[1]; //extract the filterId

        //case b.a.a: if filterId has some value
        if (filterId) {
            //case b.a.a.a: if filterId is valid
            if (output && _isSelectedFilterIdValid(filterId)) {
                api.setState('isFilterLoading', true);
                api.setState('selectedFilterId', filterId);
                api.data.load_filter.execute({
                    filterId,
                    listType
                });
                return;
            } else { //case b.a.a.a: if filterId is invalid, reset to All
                return clearFilter();
            }
        } else { //case b.a.a: if filterId is blank. Eg. encoded-query/sys_id:
            return clearFilter();
        }
    } else { //Case b.b: if encoded-query is JSON based
        //Case b.b.a: if the encoded query is generated by CB, stop further processing and return
        if (encodedQuery && (vaEncodedQueryGeneratedByCB == encodedQuery)) {
            return;
        }

        //Case b.b.b: if the encoded query comes as a param via url prop
        api.setState('vaConditionEncoded', encodedQuery);
        api.setState('vaConditionTable', PAGE_CONSTANTS.comparison_model_table);
        api.setState('isFilterLoading', true);
        api.setState('selectedFilterId', '');
    }
}
