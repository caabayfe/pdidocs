/**
 * Service for transforming simple mobile record screen metadata into full mobile metadata.
 * This service also utilizes GenAI Service to generate the metadata for Cards.
 */
class FullTransformerRecordScreenService {
    constructor() {
        this.customErrorHandler = new CustomErrorHandler(this.constructor.name);
        this.maib = new sn_mab_api.MobileComponentGenAiComposer();
        this.SOURCE_ID = "MAB W2M";
    }

    /**
     * Transforms simple mobile metadata for a record screen into full mobile metadata
     * by constructing individual components such as record screen, details screen and card components,
     * and aggregating them into a complete record screen structure.
     *
     * @param {Object} simpleMobileMetadata - The simple mobile metadata to transform.
     * @param {Array<Object>} simpleMobileMetadata.fields - An array of field objects, each representing a field of the record screen.
     * @param {string} simpleMobileMetadata.table - The name of the table associated with the record screen.
     * @param {Object} simpleMobileMetadata.references - An object containing references including view configuration.
     * @param {Object|null} simpleMobileMetadata.references.viewConfig - Optional view configuration for the components.
     * @param {string} simpleMobileMetadata.viewValue - view config sys id.
     * @returns {Object} The transformed full mobile record screen component.
     * @returns {string} return.rootTable - The root table of the record screen component.
     * @returns {string} return.rootSysId - The system identifier for the root of the record screen component.
     * @returns {Array<Object>} return.components - An array of components comprising the full record screen, including details and card components.

     * @example
     *  const simpleMobileMetadata = {
     *   componentType: "RECORD_SCREEN",
     *   viewValue: "3ed6e2b77f1012100911658f6d866584",
     *   table: "incident",
     *   fields: [
     *     {
     *       label: "Short description",
     *       prefix: "string",
     *       name: "short_description",
     *       value: "",
     *       type: "string",
     *       active: true,
     *       scalarType: "string",
     *       displayValue: "",
     *       tableLabel: "Task",
     *       display: false,
     *       display_type: "string_wide",
     *       display_type_label: "String",
     *       is_function_field: false
     *     },
     *   ],
     *   viewConfigMode: 'default',
     *   references: {
     *     viewConfig: null
     *   }
     * };
     *
     */
    transform(simpleMobileMetadata) {
        const { table, fields, viewConfigMode, references, viewValue } = simpleMobileMetadata;

        const detailsScreenComponent = this._buildDetailsScreenComponent({
            table,
            fields
        });

        const cardComponent = this._buildCardComponent({
            table,
            fields,
            viewConfigMode,
            viewConfig: references?.viewConfig,
            componentName: this._getUiViewTitle(viewValue)
        });

        const recordScreenComponent = this._buildRecordScreenComponent({
            table,
            viewValue,
            references: {
                detailsScreenComponent,
                cardComponent
            }
        });

        return {
            rootTable: recordScreenComponent.rootTable,
            rootSysId: recordScreenComponent.rootSysId,
            components: [
                recordScreenComponent,
                detailsScreenComponent,
                cardComponent
            ]
        };
    }

    /**
     * Handles the GEN_AI view config regeneration.
     *
     * @param {Object} log - The LLM conversation history provided by the MobileComponentGenAiComposer.
     * @returns {Object} The card component regenerated by the LLM.
     */
    regenerateCard(log) {
        const cardRecords = this.maib.regenerateCard(log);
        const { tableName, sysId } = cardRecords.sysSgViewConfig || {};

        return {
            rootTable: tableName,
            rootSysId: sysId,
            data: { ...cardRecords }
        };
    }

    /**
     * Builds the record screen component.
     **
     * @param {Object} params - Parameters for building the record screen component.
     * @param {string} params.table - The name of the table associated with the record screen.
     * @param {string} params.viewValue - A unique identifier for the view.
     * @param {Object} params.references - References to other components used in the record screen.
     * @param {Object} params.references.cardComponent - The card component reference.
     * @param {Object} params.references.detailsScreenComponent - The details screen component reference.
     * @returns {Object} The constructed record screen component.
     * @private
     */
    _buildRecordScreenComponent({table,viewValue, references}) {
        const { cardComponent, detailsScreenComponent } = references;

        const tableLabel = this._getTableLabel(table);
        const uiViewTitle = this._getUiViewTitle(viewValue);

        const sysSgFormScreen = this._createRecord('sys_sg_form_screen', {
            name: uiViewTitle ? `${tableLabel} - ${uiViewTitle}` : tableLabel,
            use_view_config: 'true',
            view_config: cardComponent.rootSysId || WebToMobileUtils.DEFAULT_EMPTY_VIEW_CONFIG
        });

        const sysSgFormSegment = this._createRecord('sys_sg_form_segment', {
            form: sysSgFormScreen.sysId,
            embedded_screen: detailsScreenComponent.rootSysId
        });

        return {
            rootTable: sysSgFormScreen.tableName,
            rootSysId: sysSgFormScreen.sysId,
            data: {
                sysSgFormScreen,
                sysSgFormSegment,
            }
        }
    }

    /**
     * Builds the details screen component.
     *
     * @param {Object} params - Parameters for constructing the details screen component.
     * @param {string} params.table - The name of the table associated with the details screen.
     * @param {Array<Object>} params.fields - An array of field objects representing the fields of the details screen.
     * @returns {Object} The constructed details screen component.
     * @private
     */

    _buildDetailsScreenComponent({table, fields}) {
        const sysSgDetailsScreen = this._createRecord('sys_sg_details_screen', {
            name: 'Details Screen - Details',
            table,
        });

        const sysSgScreenField = this._createScreenFields({
            fields,
            table,
            detailsScreenSysId: sysSgDetailsScreen.sysId,
        });

        return {
            rootTable: sysSgDetailsScreen.tableName,
            rootSysId: sysSgDetailsScreen.sysId,
            data: {
                sysSgDetailsScreen,
                sysSgScreenField
            }
        };
    }

    /**
     * Builds the card component using the provided table, fields, and view configuration.
     *
     * It handles different view configuration modes, such as GEN_AI, MANUAL, and DEFAULT, to create or retrieve
     * the appropriate card records.
     *
     * @param {Object} params - Parameters for building the card component.
     * @param {string} params.table - The name of the table associated with the card component.
     * @param {Array<Object>} params.fields - An array of field objects, each representing a field of the card component.
     * @param {string} params.viewConfigMode - The mode of view configuration used to create the card component.
     * @param {string} [params.viewConfig] - Optional view configuration identifier, required if viewConfigMode is MANUAL.
     * @param {string} [params.componentName] - Name of the component to build a card for.
     * @returns {Object} The constructed card component.
     * @private
     */
    _buildCardComponent({table, fields, viewConfigMode, viewConfig, componentName} ) {
        if(!viewConfigMode) {
            this.customErrorHandler.throwBadRequestError(
                'MISSING_VIEW_CONFIG_MODE',
                `The 'viewConfigMode' field is required. Please provide a valid view configuration mode.`,
            );
        }

        switch (viewConfigMode.toLowerCase()) {
            case WebToMobileUtils.viewConfigCreationModes.GEN_AI:
                return this._handleViewConfigGenAiMode(table, componentName, fields);
            case WebToMobileUtils.viewConfigCreationModes.MANUAL:
                return this._handleViewConfigManualMode(viewConfig);
            case WebToMobileUtils.viewConfigCreationModes.DEFAULT:
                return this._handleViewConfigDefaultMode(table, fields);
            default:
                this.customErrorHandler.throwBadRequestError(
                    'INVALID_VIEW_CONFIG_MODE',
                    `The view configuration mode '${viewConfigMode}' is not valid. Valid modes are: ${WebToMobileUtils.getValidViewConfigModesString()}`,
                );
        }
    }

    /**
     * Handles the MANUAL view configuration mode.
     *
     * @param {Object|null} viewConfig - The view configuration.
     * @returns {Object} An object containing the table and sys_id of the selected existing card component.
     */
    _handleViewConfigManualMode(viewConfig) {
        if (!viewConfig) {
            this.customErrorHandler.throwBadRequestError(
                'MISSING_VIEW_CONFIG',
                "The 'viewConfig' field is required. Please provide a valid view configuration."
            );
        }

        const tableName = 'sys_sg_view_config';
        const sysId = viewConfig;
        const grs = new GlideRecordSecure(tableName);

        if (!grs.get(sysId)) {
            this.customErrorHandler.throwNotFoundError(
                'VIEW_CONFIG_NOT_FOUND',
                `The sys_sg_view_config record with sys_id of '${sysId}' does not exist. Please check the 'viewConfig' parameter and try again.`
            );
        }

        return {
            rootTable: tableName,
            rootSysId: sysId,
            data: {}
        };
    }

    /**
     * Handles the DEFAULT view configuration mode.
     *
     * @param {string} table - The name of the table.
     * @param {Array<Object>} fields - The fields for the card component.
     * @returns {Object} The card component generated by script.
     */
    _handleViewConfigDefaultMode(table, fields) {
        const cardRecords = this._createCardByScript(table, fields);
        const { tableName, sysId } = cardRecords.sysSgViewConfig || {};

        return {
            rootTable: tableName,
            rootSysId: sysId,
            data: { ...cardRecords }
        };
    }

    /**
     * Handles the GEN_AI view configuration mode.
     *
     * @param {string} table - The name of the table.
     * @param {string} componentName - The name of the component.
     * @param {Array<Object>} fields - The fields for the card component.
     * @returns {Object} The card component generated by the LLM.
     */
    _handleViewConfigGenAiMode(table, componentName, fields = []) {
        const fieldNames = fields.map((field) => field.name);
        const cardRecords = this.maib.generateCard(table, componentName, fieldNames);
        const { tableName, sysId } = cardRecords.sysSgViewConfig || {};

        return {
            rootTable: tableName,
            rootSysId: sysId,
            data: { ...cardRecords }
        };
    }

    /**
     * Creates screen fields from the provided fields metadata.
     **
     * @param {Object} params - Destructured object containing fields, details screen system ID, and table name.
     * @param {Object[]} params.fields - An array of field objects, each representing a field for the screen.
     * @param {string} params.detailsScreenSysId - The system ID of the details screen to which the fields belong.
     * @param {string} params.table - The name of the table associated with the screen fields.
     * @returns {Array<Object>} An array of created screen field records.
     * @private
     */
    _createScreenFields(params) {
        const { fields, detailsScreenSysId, table } = params;
        return fields.map((field, index) => {
            let type = 'auto';
            if (field.type === 'audio' || field.type === 'file_attachment') {
                type = 'file';
            }

            return this._createRecord('sys_sg_screen_field', {
                screen: detailsScreenSysId,
                data_item_field_name: field.name,
                type,
                screen_data_item_table: table,
                order: WebToMobileUtils.getOrderString(index)
            });
        });
    }

    /**
     * Creates a card by script using the W2M default view template.
     *
     * @param {string} table - The name of the table for which the card is created.
     * @param {Array<Object>} columns - An array of column objects representing the fields for the card.
     * @returns {Object} The card records containing view configuration, elements, and attributes.
     * @private
     */
    _createCardByScript(table, columns) {
        const MAB_W2M_DEFAULT_VIEW_TEMPLATE = '0c0b9242bd559e90f877dac13f131058';
        const cardElementAttributeMap = WebToMobileUtils.getMapFromTable(
            'sys_sg_view_element_attribute_name',
            'name',
            'sys_id'
        );

        const sysSgViewTemplateSlots = WebToMobileUtils.getRecords(
            'sys_sg_view_template_slot',
            ['name', 'sys_id'],
            { view_template: MAB_W2M_DEFAULT_VIEW_TEMPLATE }
        );

        const sortedSysSgViewTemplateSlots = sysSgViewTemplateSlots.sort(
            (slot1, slot2) =>  slot1.name.localeCompare(slot2.name)
        );

        const sysSgViewConfig = WebToMobileUtils.createRecord('sys_sg_view_config', {
            name: `${this._getTableLabel(table)} - Record Screen Card`,
            table,
            template: MAB_W2M_DEFAULT_VIEW_TEMPLATE,
            creation_method: this.SOURCE_ID
        });

        const sysSgViewConfigElement = sortedSysSgViewTemplateSlots.map((cardTemplateElement, index) => {
            return WebToMobileUtils.createRecord('sys_sg_view_config_element', {
                name: `${cardTemplateElement.name}_element`,
                view_config: sysSgViewConfig.sysId,
                view_template_slot: cardTemplateElement.sys_id,
                creation_method: this.SOURCE_ID
            });
        });

        const sysSgViewConfigElementAttribute = sysSgViewConfigElement.reduce((attributes, cardElement, index) => {
            const columnIndex = Math.floor(index / 2);
            if (columnIndex < columns.length) {
                const column = columns[columnIndex];
                const cardElementAttributeType = (index % 2 === 0) ? 'FieldLabel' : 'FieldValue';

                const sysSgViewConfigElementAttribute = WebToMobileUtils.createRecord(
                    'sys_sg_view_config_element_attribute',
                    {
                        name: cardElementAttributeMap[cardElementAttributeType],
                        view_config_element: cardElement.sysId,
                        value: column.name,
                        description: `${cardElement.fields.name}_${cardElementAttributeType}`,
                        creation_method: this.SOURCE_ID
                    });

                attributes.push(sysSgViewConfigElementAttribute);
            }
            return attributes;
        }, []);

        return {
            sysSgViewConfig,
            sysSgViewConfigElement,
            sysSgViewConfigElementAttribute
        };
    }

    /**
     * Creates a record in the specified table with given data.
     *
     * @param {string} table - The table where the record will be created.
     * @param {Object} data - The data for the record.
     * @returns {Object} The created record.
     * @private
     */
    _createRecord(table, data) {
        return WebToMobileUtils.createRecord(table, data);
    }


    /**
     * Retrieves the label of a table by its name.
     *
     * @param {string} tableName - The name of the table.
     * @returns {string|null} The label of the table, or null if not found.
     */
    _getTableLabel(tableName) {
        const records = WebToMobileUtils.getRecords(
            'sys_db_object',
            ['label'],
            { name: tableName }
        );
        const dbViews = WebToMobileUtils.getRecords(
			'sys_db_view',
			['label'],
			{ name: tableName }
		);

		if(records.length > 0) {
			return records[0].label;
		} else if (dbViews.length > 0) {
			return dbViews[0].label || tableName;
		} else {
			return null;
		}
    }

    /**
     * Retrieves the name of a UI view by its sys_id.
     *
     * @param {string} viewSysId - The sys_id of the UI view.
     * @returns {string|null} The name of the UI view, or null if not found.
     */
    _getUiViewTitle(viewSysId) {
        const records = WebToMobileUtils.getRecords(
            'sys_ui_view',
            ['title'],
            { sys_id: viewSysId }
        );
        return records.length > 0 ? records[0].title : null;
    }
}

module.exports = FullTransformerRecordScreenService;
