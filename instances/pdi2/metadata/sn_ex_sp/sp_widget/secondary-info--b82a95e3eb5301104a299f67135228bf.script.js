(function() {
    data.tabName = '';
    if (options) {
        if (options.table) {
            data.table = options.table;
        }
        if (options.sysId) {
            data.sysId = options.sysId;
        }
        if (options.tabs) {
            data.tabs = options.tabs;
        }
        if (options.tabName) {
            data.tabName = options.tabName;
        }
    }
})();
