/**
 * @param {params} params
 * @param {api} params.api
 * @param {any} params.event
 * @param {any} params.imports
 * @param {ApiHelpers} params.helpers
 */
async function handler({
    api,
    event,
    helpers,
    imports
}) {
    const showAiRecordIndicators = event.payload?.isAiCreated;
    const recordDisplayValue = api.data?.glide_form_1?.nowRecordCommonHeader?.recordDisplayValue;
    api.setState("showAiRecordIndicators", showAiRecordIndicators);

    if (showAiRecordIndicators) {
        api.emit("CTRL_RECORD#ADD_NOTIFICATION", {
            "items": [{
                "message": await helpers.translate("[{0}] generated by AI. Check for accuracy.", recordDisplayValue),
                "type": "suggestion",
                "id": "aiGeneratedRecordPageNotification"
            }]
        });
    }
}
