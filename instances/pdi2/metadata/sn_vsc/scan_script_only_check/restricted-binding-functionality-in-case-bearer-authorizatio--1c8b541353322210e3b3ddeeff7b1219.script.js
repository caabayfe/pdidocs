(function(finding) {
    // In a safe system, for each oauth_entity entry, we should have the following conditions met:
    // 1- restricted_binding set to true
    // AND
    // 2- Glide property glide.oauth.enforce_restricted_binding_for_ui set to true
    active_plugin = GlidePluginManager.isActive('com.snc.platform.security.oauth');
    //If the plugin is active, confirm there is at least 1 active IP based rule
    if (active_plugin) {
        var targetProperty = 'glide.oauth.enforce_restricted_binding_for_ui';
        var expectedValue = 'true';
        var defaultValue = 'false';
        var propertyValue = gs.getProperty(targetProperty, defaultValue);
        // Query to see if any oauth_entry has restricted_binding to false
        var gr1 = new GlideRecord('oauth_entity');
        gr1.query("restricted_binding", "false");
        // If we find one single means there is a risk with tokens generated by that entity
        if (gr1.next()) {
            finding.setCurrentSource(gr1);
            finding.increment();
        } else if (propertyValue.toLowerCase() != expectedValue.toLowerCase()) { // Otherwise if all restricted_binding are true we check if the Glide Property is not set to secure state
            
            var gr = new GlideRecord('sys_properties');
            gr.get('name', targetProperty);
            finding.setCurrentSource(gr);
            finding.increment();
        }
    }
})(finding);
